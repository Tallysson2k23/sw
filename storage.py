"""Local files in development; a private S3-compatible bucket in production."""
import re
from pathlib import Path
from urllib.parse import urlparse
import boto3
from botocore.config import Config
from botocore.exceptions import BotoCoreError, ClientError
from flask import abort, redirect, send_file
from werkzeug.utils import secure_filename


class Storage:
    def __init__(self, config):
        self.remote = config.get('STORAGE_BACKEND') == 's3'
        self.folder = Path(config['UPLOAD_FOLDER'])
        self.origin = None
        self.client = None
        if not self.remote:
            self.folder.mkdir(parents=True, exist_ok=True)
            return
        required = ['S3_ENDPOINT_URL', 'S3_BUCKET', 'S3_ACCESS_KEY_ID', 'S3_SECRET_ACCESS_KEY']
        if any(not config.get(key) for key in required):
            raise RuntimeError('Configure endpoint, bucket e credenciais do armazenamento S3.')
        endpoint = urlparse(config['S3_ENDPOINT_URL'])
        if endpoint.scheme != 'https' or not endpoint.netloc or endpoint.username or endpoint.password or endpoint.query or endpoint.fragment or endpoint.path not in ['', '/']:
            raise RuntimeError('S3_ENDPOINT_URL deve ser a origem HTTPS do provedor, sem bucket ou credenciais na URL.')
        self.origin = f'https://{endpoint.netloc}'
        self.bucket = config['S3_BUCKET']
        self.client = boto3.client('s3', endpoint_url=config['S3_ENDPOINT_URL'],
            region_name=config.get('S3_REGION', 'auto'),
            aws_access_key_id=config['S3_ACCESS_KEY_ID'], aws_secret_access_key=config['S3_SECRET_ACCESS_KEY'],
            config=Config(signature_version='s3v4', s3={'addressing_style': 'path'}, connect_timeout=5, read_timeout=20, retries={'max_attempts': 2}))

    @staticmethod
    def key(name):
        # Keys are generated by the application, never paths submitted by users.
        if not re.fullmatch(r'[a-f0-9]{48}\.(?:jpg|jpeg|png|pdf)', name):
            raise ValueError('Nome de arquivo inválido.')
        return name

    def put(self, name, data, mime):
        name = self.key(name)
        if self.remote:
            self.client.put_object(Bucket=self.bucket, Key=name, Body=data, ContentType=mime, CacheControl='private, no-store')
        else: (self.folder/name).write_bytes(data)

    def delete(self, name):
        name = self.key(name)
        if self.remote: self.client.delete_object(Bucket=self.bucket, Key=name)
        else: (self.folder/name).unlink(missing_ok=True)

    def response(self, name, mime, download_name=None):
        name = self.key(name)
        if self.remote:
            params = {'Bucket': self.bucket, 'Key': name, 'ResponseContentType': mime,
                      'ResponseCacheControl': 'private, no-store'}
            if download_name:
                filename = secure_filename(download_name) or 'material'
                params['ResponseContentDisposition'] = f'attachment; filename="{filename}"'
            # Authorization is checked by the route BEFORE issuing this short-lived URL.
            return redirect(self.client.generate_presigned_url('get_object', Params=params, ExpiresIn=60), code=302)
        if not (self.folder/name).is_file(): abort(404)
        return send_file(self.folder/name, mimetype=mime, download_name=download_name, as_attachment=bool(download_name))
